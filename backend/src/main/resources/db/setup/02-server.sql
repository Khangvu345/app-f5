CREATE TABLE giftmate.event_recipients (
    event_id BIGINT NOT NULL REFERENCES giftmate.events(id) ON DELETE CASCADE,
    recipient_id BIGINT NOT NULL REFERENCES giftmate.recipients(id) ON DELETE CASCADE,
    is_primary BOOLEAN NOT NULL DEFAULT false,
