-- Thiết kế PostgreSQL GĐ1. Chạy trên database thiết kế trống.
-- Backend đang chạy dùng Flyway trong db/migration.
BEGIN;
CREATE SCHEMA giftmate;

CREATE TABLE giftmate.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) UNIQUE CHECK (email = lower(email) AND btrim(email) <> ''),
    password_hash VARCHAR(255),
    auth_provider VARCHAR(20) NOT NULL CHECK (auth_provider IN ('EMAIL', 'GOOGLE', 'APPLE')),
    provider_subject VARCHAR(255),
    role VARCHAR(20) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'ADMIN')),
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED', 'DELETED')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    UNIQUE (auth_provider, provider_subject),
    CHECK ((auth_provider = 'EMAIL' AND email IS NOT NULL AND password_hash IS NOT NULL)
        OR (auth_provider IN ('GOOGLE', 'APPLE') AND provider_subject IS NOT NULL AND btrim(provider_subject) <> ''))
);

CREATE TABLE giftmate.user_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES giftmate.users(id) ON DELETE CASCADE,
    display_name VARCHAR(100) NOT NULL CHECK (btrim(display_name) <> ''),
    plan_type VARCHAR(20) NOT NULL DEFAULT 'FREE' CHECK (plan_type IN ('FREE', 'PREMIUM')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE giftmate.refresh_tokens (
    id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES giftmate.users(id) ON DELETE CASCADE,
    token_hash VARCHAR(255) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_refresh_tokens_user ON giftmate.refresh_tokens(user_id);
CREATE INDEX ix_refresh_tokens_expiry ON giftmate.refresh_tokens(expires_at) WHERE revoked_at IS NULL;

CREATE FUNCTION giftmate.touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON giftmate.users
FOR EACH ROW EXECUTE FUNCTION giftmate.touch_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON giftmate.user_settings
FOR EACH ROW EXECUTE FUNCTION giftmate.touch_updated_at();

COMMIT;
