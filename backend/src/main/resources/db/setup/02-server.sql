-- GiftMate v2.2 | Run in the giftmate database.
BEGIN;
CREATE SCHEMA giftmate;

CREATE TABLE giftmate.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) UNIQUE,
    password_hash VARCHAR(255),
    refresh_token_hash TEXT,
    auth_provider VARCHAR(20),
    provider_subject VARCHAR(255),
    role VARCHAR(20) NOT NULL DEFAULT 'USER',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CHECK (auth_provider IN ('EMAIL', 'GOOGLE', 'APPLE')),
    CHECK (role IN ('USER', 'ADMIN')),
    CHECK (status IN ('ACTIVE', 'DISABLED', 'DELETED')),
    CHECK (email = lower(email)),
    UNIQUE (auth_provider, provider_subject)
);

CREATE TABLE giftmate.user_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES giftmate.users(id) ON DELETE CASCADE UNIQUE,
    display_name VARCHAR(100) NOT NULL,
    timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    locale VARCHAR(10) NOT NULL DEFAULT 'vi',
    currency CHAR(3) NOT NULL DEFAULT 'VND',
    default_reminder_time TIME NOT NULL DEFAULT '09:00',
    default_reminder_offsets INT[] NOT NULL DEFAULT '{14,7,3,1,0}',
    notifications_enabled BOOLEAN NOT NULL DEFAULT true,
    hide_gift_on_lockscreen BOOLEAN NOT NULL DEFAULT true,
    ai_enabled BOOLEAN NOT NULL DEFAULT true,
    plan_type VARCHAR(20) NOT NULL DEFAULT 'FREE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (plan_type IN ('FREE', 'PREMIUM')),
    CHECK (default_reminder_offsets <@ ARRAY[14,7,3,1,0])
);

CREATE TABLE giftmate.plan_limits (
    plan_type VARCHAR(20) NOT NULL,
    limit_key VARCHAR(50) NOT NULL,
    limit_value INT,
    unit VARCHAR(20),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (plan_type IN ('FREE', 'PREMIUM')),
    CHECK (limit_key IN ('recipient_limit', 'ai_requests_per_day', 'active_gift_ideas')),
    PRIMARY KEY (plan_type, limit_key)
);

CREATE TABLE giftmate.recipients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES giftmate.users(id) ON DELETE CASCADE,
    name VARCHAR(150) NOT NULL,
    relationship VARCHAR(50),
    relationship_detail VARCHAR(100),
    age_group VARCHAR(20),
    birth_day SMALLINT,
    birth_month SMALLINT,
    birth_year SMALLINT,
    notes VARCHAR(500),
    is_favourite BOOLEAN NOT NULL DEFAULT false,
    version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CHECK (relationship IN ('FAMILY', 'FRIEND', 'PARTNER', 'COLLEAGUE', 'TEACHER', 'OTHER')),
    CHECK (age_group IN ('CHILD', 'TEEN', 'ADULT', 'SENIOR', 'UNKNOWN')),
    CHECK (btrim(name) <> ''),
    CHECK (birth_day BETWEEN 1 AND 31),
    CHECK (birth_month BETWEEN 1 AND 12),
    CHECK ((birth_day IS NULL) = (birth_month IS NULL))
);

CREATE TABLE giftmate.recipient_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL REFERENCES giftmate.recipients(id) ON DELETE CASCADE,
    category VARCHAR(80) NOT NULL,
    value VARCHAR(200) NOT NULL,
    polarity VARCHAR(20) NOT NULL,
    source VARCHAR(20) NOT NULL DEFAULT 'USER',
    confirmed_at TIMESTAMPTZ,
    is_active BOOLEAN NOT NULL DEFAULT true,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CHECK (polarity IN ('LIKE', 'DISLIKE', 'AVOID')),
    CHECK (source IN ('USER', 'AI_INFERRED'))
);

CREATE TABLE giftmate.events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES giftmate.users(id) ON DELETE CASCADE,
    title VARCHAR(150) NOT NULL,
    event_type VARCHAR(50) NOT NULL,
    occasion_type VARCHAR(50),
    calendar_type VARCHAR(20) NOT NULL DEFAULT 'SOLAR',
    original_day SMALLINT NOT NULL,
    original_month SMALLINT NOT NULL,
    original_year SMALLINT,
    is_year_known BOOLEAN NOT NULL DEFAULT true,
    is_lunar_leap_month BOOLEAN NOT NULL DEFAULT false,
    recurrence_frequency VARCHAR(20) NOT NULL DEFAULT 'ANNUAL',
    leap_day_policy VARCHAR(20),
    timezone VARCHAR(64) NOT NULL DEFAULT 'Asia/Ho_Chi_Minh',
    start_date DATE,
    end_date DATE,
    default_budget NUMERIC(18,2),
    notes VARCHAR(500),
    version INT NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CHECK (event_type IN ('BIRTHDAY', 'ANNIVERSARY', 'WEDDING', 'GRADUATION', 'HOLIDAY', 'CUSTOM')),
    CHECK (occasion_type IN ('BIRTHDAY', 'ANNIVERSARY', 'HOLIDAY', 'OTHER')),
    CHECK (calendar_type IN ('SOLAR', 'LUNAR')),
    CHECK (recurrence_frequency IN ('NONE', 'ANNUAL')),
    CHECK (leap_day_policy IN ('FEB28', 'MAR01', 'SKIP')),
    CHECK (btrim(title) <> ''),
    CHECK (original_day BETWEEN 1 AND 31),
    CHECK (original_month BETWEEN 1 AND 12),
    CHECK (end_date >= start_date),
    CHECK (default_budget > 0)
