CREATE FUNCTION giftmate.check_events_recipient() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    parent_id bigint;
BEGIN
    IF TG_TABLE_NAME = 'events' THEN
        parent_id := NEW.id;
    ELSE
        parent_id := OLD.event_id;
    END IF;

    -- Serialize concurrent removals for the same parent.
    PERFORM 1 FROM giftmate.events WHERE id = parent_id FOR NO KEY UPDATE;

    IF FOUND AND NOT EXISTS (
        SELECT 1 FROM giftmate.event_recipients WHERE event_id = parent_id
    ) THEN
        RAISE EXCEPTION 'events % must have at least one recipient', parent_id
            USING ERRCODE = '23514';
    END IF;

    RETURN NULL;
END;
$$;

CREATE CONSTRAINT TRIGGER require_recipient
AFTER INSERT OR UPDATE OF id ON giftmate.events DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION giftmate.check_events_recipient();

CREATE CONSTRAINT TRIGGER keep_recipient
AFTER DELETE OR UPDATE OF event_id ON giftmate.event_recipients DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION giftmate.check_events_recipient();

