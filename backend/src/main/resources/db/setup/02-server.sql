-- Proposed lifecycle. Confirm the transition policy with the team.
CREATE FUNCTION giftmate.check_gift_status() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.status IS DISTINCT FROM OLD.status THEN
        IF NOT (
            (OLD.status = 'IDEA' AND NEW.status IN ('CONSIDERING', 'SELECTED', 'CANCELLED')) OR
            (OLD.status = 'CONSIDERING' AND NEW.status IN ('IDEA', 'SELECTED', 'CANCELLED')) OR
            (OLD.status = 'SELECTED' AND NEW.status IN ('CONSIDERING', 'PURCHASED', 'CANCELLED')) OR
            (OLD.status = 'PURCHASED' AND NEW.status IN ('GIVEN', 'RETURNED', 'CANCELLED')) OR
            (OLD.status = 'GIVEN' AND NEW.status = 'RETURNED')
        ) THEN
            RAISE EXCEPTION 'Invalid gift status transition % -> %', OLD.status, NEW.status
                USING ERRCODE = '23514';
        END IF;
        NEW.status_changed_at := now();
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER check_gift_status BEFORE UPDATE OF status ON giftmate.gifts
FOR EACH ROW EXECUTE FUNCTION giftmate.check_gift_status();

CREATE VIEW giftmate.v_actual_expenses AS
SELECT e.*
FROM giftmate.expenses e
LEFT JOIN giftmate.gifts g ON g.id = e.gift_id
WHERE e.deleted_at IS NULL AND e.is_counted_in_actual_spend
    AND (e.gift_id IS NULL OR (g.deleted_at IS NULL AND g.status NOT IN ('RETURNED', 'CANCELLED')));

CREATE VIEW giftmate.v_annual_spend AS
SELECT user_id, EXTRACT(YEAR FROM occurred_at)::smallint AS scope_year, currency,
       SUM(amount) AS actual_spend
FROM giftmate.v_actual_expenses
GROUP BY user_id, EXTRACT(YEAR FROM occurred_at), currency;

CREATE VIEW giftmate.v_occurrence_spend AS
SELECT user_id, occurrence_id, currency, SUM(amount) AS actual_spend
FROM giftmate.v_actual_expenses
WHERE occurrence_id IS NOT NULL
GROUP BY user_id, occurrence_id, currency;

