    recipient_id BIGINT NOT NULL REFERENCES giftmate.recipients(id) ON DELETE CASCADE,
    occurrence_id BIGINT REFERENCES giftmate.event_occurrences(id) ON DELETE SET NULL,
    suggestion_id BIGINT,
