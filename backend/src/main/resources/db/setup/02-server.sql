    category VARCHAR(80),
    source VARCHAR(20) NOT NULL DEFAULT 'MANUAL',
    status VARCHAR(20) NOT NULL DEFAULT 'IDEA',
    status_changed_at TIMESTAMPTZ,
    canonical_key VARCHAR(150),
    product_url TEXT,
    image_url TEXT,
    estimated_amount NUMERIC(18,2),
    purchased_on DATE,
    given_on DATE,
    follow_up_prompted_at TIMESTAMPTZ,
    follow_up_dismissed_at TIMESTAMPTZ,
    note TEXT,
