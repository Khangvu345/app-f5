-- PostgreSQL GiftMate GĐ1. Manual equivalent of V3 for a database with V1 and V2 applied.
-- Normal Docker use: Flyway applies V3 at backend startup; do not run this script afterward.
BEGIN;
CREATE SCHEMA giftmate;

-- Extend the existing account table from V1 instead of creating a duplicate.
-- V2 already owns public.refresh_tokens, so this script does not create another token table.
DO $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM public.users WHERE email IS NOT NULL AND btrim(email) = ''
    ) THEN
        RAISE EXCEPTION 'Cannot normalize blank users.email values before V3';
    END IF;
    IF EXISTS (
        SELECT lower(btrim(email))
        FROM public.users
        WHERE email IS NOT NULL
        GROUP BY lower(btrim(email))
        HAVING count(*) > 1
    ) THEN
        RAISE EXCEPTION 'Cannot normalize users.email: case-insensitive duplicates exist';
    END IF;
END;
$$;

UPDATE public.users
SET email = lower(btrim(email))
WHERE email IS NOT NULL AND email <> lower(btrim(email));

ALTER TABLE public.users
    ALTER COLUMN email DROP NOT NULL,
    ALTER COLUMN password_hash DROP NOT NULL,
    ADD COLUMN auth_provider VARCHAR(20) NOT NULL DEFAULT 'EMAIL',
    ADD COLUMN provider_subject VARCHAR(255),
    ADD COLUMN role VARCHAR(20) NOT NULL DEFAULT 'USER',
    ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    ADD COLUMN deleted_at TIMESTAMPTZ,
    ADD CONSTRAINT users_email_normalized_check
        CHECK (email IS NULL OR (email = lower(email) AND btrim(email) <> '')),
    ADD CONSTRAINT users_auth_provider_check
        CHECK (auth_provider IN ('EMAIL', 'GOOGLE', 'APPLE')),
    ADD CONSTRAINT users_role_check CHECK (role IN ('USER', 'ADMIN')),
    ADD CONSTRAINT users_status_check CHECK (status IN ('ACTIVE', 'DISABLED', 'DELETED')),
    ADD CONSTRAINT users_provider_subject_unique UNIQUE (auth_provider, provider_subject),
    ADD CONSTRAINT users_provider_identity_check
        CHECK ((auth_provider = 'EMAIL' AND email IS NOT NULL AND password_hash IS NOT NULL)
            OR (auth_provider IN ('GOOGLE', 'APPLE') AND provider_subject IS NOT NULL
                AND btrim(provider_subject) <> ''));

CREATE TABLE giftmate.user_settings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES public.users(id) ON DELETE CASCADE,
    display_name VARCHAR(100) NOT NULL CHECK (btrim(display_name) <> ''),
    plan_type VARCHAR(20) NOT NULL DEFAULT 'FREE' CHECK (plan_type IN ('FREE', 'PREMIUM')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Preserve account names for users created before the settings table existed.
INSERT INTO giftmate.user_settings (user_id, display_name)
SELECT id, left(COALESCE(NULLIF(btrim(full_name), ''), NULLIF(btrim(email), ''), 'GiftMate'), 100)
FROM public.users
ON CONFLICT (user_id) DO NOTHING;

CREATE FUNCTION giftmate.touch_updated_at() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER set_updated_at BEFORE UPDATE ON public.users
FOR EACH ROW EXECUTE FUNCTION giftmate.touch_updated_at();
CREATE TRIGGER set_updated_at BEFORE UPDATE ON giftmate.user_settings
FOR EACH ROW EXECUTE FUNCTION giftmate.touch_updated_at();

COMMIT;
