CREATE TABLE giftmate.budgets (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES giftmate.users(id) ON DELETE CASCADE,
    scope_type VARCHAR(20) NOT NULL,
    scope_year SMALLINT,
    occurrence_id BIGINT REFERENCES giftmate.event_occurrences(id) ON DELETE CASCADE,
    amount NUMERIC(18,2) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'VND',
    alert_threshold_percent SMALLINT NOT NULL DEFAULT 80,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    deleted_at TIMESTAMPTZ,
    CHECK (scope_type IN ('ANNUAL', 'EVENT')),
    CHECK (scope_type <> 'ANNUAL' OR scope_year IS NOT NULL),
    CHECK (scope_type <> 'EVENT' OR occurrence_id IS NOT NULL),
    CHECK (amount > 0),
    CHECK (alert_threshold_percent BETWEEN 1 AND 100)
