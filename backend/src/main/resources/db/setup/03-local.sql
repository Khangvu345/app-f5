-- GiftMate v2.2 | PostgreSQL reference for device-only storage.
-- Run in a separate giftmate_local database. No physical server foreign keys.
BEGIN;
CREATE SCHEMA giftmate_local;

CREATE TABLE giftmate_local.sync_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type VARCHAR(50) NOT NULL,
    entity_id BIGINT NOT NULL,
    operation VARCHAR(20) NOT NULL,
    payload_json TEXT NOT NULL,
    retry_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (operation IN ('INSERT', 'UPDATE', 'DELETE'))
);

CREATE TABLE giftmate_local.sync_state (
    entity_type VARCHAR(50) NOT NULL,
    last_synced_at TIMESTAMPTZ,
    PRIMARY KEY (entity_type)
);

CREATE TABLE giftmate_local.app_settings_local (
    key VARCHAR(50) NOT NULL,
    value TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (key)
);

CREATE TABLE giftmate_local.notification_schedules (
    notification_id BIGINT NOT NULL,
    local_notification_id VARCHAR(100),
    scheduled_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(20) NOT NULL,
    CHECK (status IN ('SCHEDULED', 'SENT', 'CANCELLED')),
    PRIMARY KEY (notification_id)
);

CREATE TABLE giftmate_local.occurrence_tasks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    occurrence_id BIGINT NOT NULL,
    gift_id BIGINT,
    title VARCHAR(200) NOT NULL,
    due_on DATE,
    completed_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE giftmate_local.ai_cache (
    request_key VARCHAR(150) NOT NULL,
    response_json TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (request_key)
);

CREATE TABLE giftmate_local.draft_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL,
    category VARCHAR(80) NOT NULL,
    value VARCHAR(200) NOT NULL,
    polarity VARCHAR(20) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (polarity IN ('LIKE', 'DISLIKE', 'AVOID'))
);

CREATE TABLE giftmate_local.ai_draft (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    recipient_id BIGINT,
    occurrence_id BIGINT,
    form_json TEXT NOT NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE giftmate_local.image_cache (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url TEXT NOT NULL,
    local_path TEXT,
    cached_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

COMMENT ON COLUMN giftmate_local.sync_outbox.entity_id IS
    'Server BIGINT when known. Before sync, use an app-assigned temporary BIGINT and keep any UUID in payload_json.';
COMMENT ON COLUMN giftmate_local.notification_schedules.notification_id IS
    'Logical reference to giftmate.notifications.id';
COMMENT ON COLUMN giftmate_local.occurrence_tasks.occurrence_id IS
    'Logical reference to giftmate.event_occurrences.id';
COMMENT ON COLUMN giftmate_local.occurrence_tasks.gift_id IS
    'Logical reference to giftmate.gifts.id';
COMMENT ON COLUMN giftmate_local.draft_preferences.recipient_id IS
    'Logical reference to giftmate.recipients.id';
COMMIT;
