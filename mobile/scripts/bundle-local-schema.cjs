/* global __dirname */
// Keep the Expo bundle byte-for-byte equivalent to the canonical SQLite scripts.
const fs = require('node:fs');
const path = require('node:path');

const prettier = require('prettier');
const root = path.resolve(__dirname, '../../backend/src/main/resources/db/setup');
const scripts = [
  ['LOCAL_SCHEMA', '03-local.sql'],
  ['LOCAL_MIGRATION_PREPARE_V1', '05-chuan-bi-v1.sql'],
  ['LOCAL_MIGRATION_RESTORE_V2', '06-khoi-phuc-v2.sql'],
];
async function main() {
  const source = `// Generated by scripts/bundle-local-schema.cjs; do not edit.\n${scripts
    .map(
      ([name, file]) =>
        `export const ${name} = ${JSON.stringify(fs.readFileSync(path.join(root, file), 'utf8'))};`,
    )
    .join('\n')}\n`;
  const destination = path.resolve(__dirname, '../src/services/storage/local-schema.ts');
  const options = (await prettier.resolveConfig(destination)) || {};
  const output = await prettier.format(source, { ...options, filepath: destination });
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(destination, 'utf8') !== output) {
      console.error('SQLite bundle differs from canonical scripts');
      process.exitCode = 1;
    }
  } else {
    fs.writeFileSync(destination, output);
  }
}
main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});
